@Test @MainActor func pasteboardAdapterExactTextMarkersAndSources() async throws {
    let board = NSPasteboard.withUniqueName()
    defer { board.releaseGlobally() }
    let adapter = SystemClipboard(board: board)
    let repository = try SQLiteHistory(path: ":memory:")
    let capture = CaptureService(clipboard: adapter, history: repository)
    for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        let item = NSPasteboardItem()
        item.setString("must not save", forType: .string)
        item.setData(Data(), forType: .init(marker))
        board.clearContents(); #expect(board.writeObjects([item]))
        #expect(adapter.read().protected)
        #expect(!(try await capture.tick(sourceFallback: nil)))
    }
    let exact = "\tПривет 👋\r\n \0end"
    let item = NSPasteboardItem()
    item.setString(exact, forType: .string)
    item.setString("test.source", forType: .init("org.nspasteboard.source"))
    board.clearContents(); #expect(board.writeObjects([item]))
    #expect(try await capture.tick(sourceFallback: "fallback.app"))
    let entries = try await repository.entries()
    #expect(entries.count == 1)
    #expect(entries.first?.text.utf8.elementsEqual(exact.utf8) == true)
    #expect(entries.first?.source == "test.source")
    let own = try adapter.write("self")
    #expect(own == board.changeCount)
    #expect(adapter.read().protected)
    #expect(!(try await capture.tick(sourceFallback: nil)))
    let file = NSPasteboardItem()
    file.setString("file:///tmp/example.txt", forType: .fileURL)
    file.setString("example.txt", forType: .string)
    board.clearContents(); #expect(board.writeObjects([file]))
    #expect(adapter.read().text == nil)
    let a = NSPasteboardItem(), b = NSPasteboardItem()
    a.setString("first", forType: .string); b.setString("second", forType: .string)
    board.clearContents(); #expect(board.writeObjects([a, b]))
    #expect(adapter.read().text == nil)
}

@Test @MainActor func commandVResolvesInInstalledLayoutsWithoutSwitchingSystemLayout() throws {
    let identifiers = ["com.apple.keylayout.US", "com.apple.keylayout.Russian", "com.apple.keylayout.Dvorak"]
    for identifier in identifiers {
        let filter = [kTISPropertyInputSourceID as String: identifier] as CFDictionary
        let list = TISCreateInputSourceList(filter, true).takeRetainedValue() as! [TISInputSource]
        let source = try #require(list.first, "System keyboard layout should be available: \(identifier)")
        let key = try #require(PasteKeyResolver.keyCode(in: source))
        if identifier == "com.apple.keylayout.US" { #expect(key == 9) }
        if identifier == "com.apple.keylayout.Dvorak" { #expect(key != 9) }
    }
}

@Test @MainActor func shortcutRegistrationReplacementAndRejectedPaste() throws {
    let shortcut = GlobalShortcut()
    let modifiers = UInt32(controlKey | optionKey | cmdKey | shiftKey)
    try shortcut.register(Shortcut(keyCode: 79, modifiers: modifiers, label: "Test F18"))
    try shortcut.register(Shortcut(keyCode: 80, modifiers: modifiers, label: "Test F19"))
    #expect(throws: StorageError.self) {
        try shortcut.register(Shortcut(keyCode: 9, modifiers: UInt32(cmdKey), label: "⌘V"))
    }
    #expect(throws: StorageError.self) {
        try shortcut.register(Shortcut(keyCode: 9, modifiers: UInt32(cmdKey | shiftKey), label: "⌘⇧V"))
    }
    try shortcut.register(nil)
    try shortcut.register(Shortcut(keyCode: 79, modifiers: modifiers, label: "Test F18"))
    try shortcut.register(nil)
}
