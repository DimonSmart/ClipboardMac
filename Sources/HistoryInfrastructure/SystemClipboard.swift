import AppKit
import HistoryServices

@MainActor public final class SystemClipboard: ClipboardPort {
    private let board: NSPasteboard
    public init(board: NSPasteboard = .general) { self.board = board }
    public var changeCount: Int { board.changeCount }
    public var permission: ClipboardPermission { board.accessBehavior == .alwaysAllow ? .allowed : .requiresAccess }
    public func requestAccessOnce() {
        // Explicit user action only. Polling never reads while Ask/Denied is configured.
        guard board.accessBehavior != .alwaysDeny else { return }
        _ = board.string(forType: .string)
    }
    public func read() -> ClipboardSample {
        let count = board.changeCount
        guard permission == .allowed else { return ClipboardSample(change: count, text: nil) }
        let blocked = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: blocked), !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              let items = board.pasteboardItems, items.count == 1, let item = items.first else {
            return ClipboardSample(change: count, text: nil, protected: true)
        }
        let sourceValue = item.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source"))
        let source = sourceValue.flatMap { value in
            value.range(of: "^[A-Za-z0-9_-]+(\\.[A-Za-z0-9_-]+)+$", options: .regularExpression) != nil ? value : nil
        }
        return ClipboardSample(change: count, text: item.string(forType: .string), source: source)
    }
    public func write(_ text: String) throws -> Int {
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { throw StorageError(message: "Could not prepare the selected text.") }
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let ownChange = board.clearContents()
        guard board.writeObjects([item]) else { throw StorageError(message: "Could not copy the selected text.") }
        return ownChange
    }
}
